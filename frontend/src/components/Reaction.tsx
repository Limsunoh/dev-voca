"use client";

import { useId } from "react";

import { Boss, Student } from "@/components/ReactionCharacters";

/**
 * 채점 뒤 판정 연출. 부장님이 무대로 걸어와 학생을 쓰다듬거나 콩 때린다.
 *
 * **디자인 원본을 옮긴 것이다**(`components/quiz/Reaction.jsx` + `tokens/motion.css`).
 * 크림 디자인을 적용할 때 이 자리에 졸라맨을 손으로 그려 넣었던 것을
 * 원본으로 되돌렸다.
 *
 * ## 순서 - 왜 어둡게 깔아야 하는가
 *
 *     0%        화면이 어두워지고 원형 무대가 열린다
 *     10~56%    부장님이 왼쪽에서 다섯 걸음 걸어온다
 *     56~66%    팔을 들어 내린다
 *     66~70%    **닿는 순간.** 무대 바닥이 초록/코랄로 넘어가고 링이 퍼진다
 *     67%       표정이 바뀐다(웃음/굳음, 기쁨/아픔)
 *     74~92%    판정 글자가 떴다 사라진다
 *     78~100%   어둠이 걷힌다
 *     90~100%   층 전체가 걷힌다
 *
 * **마지막 한 줄이 없으면 사람이 화면에 박힌다.** 원본 키프레임은 걸어온
 * 자리에 선 채로 끝나서, 지우는 것이 따로 있어야 한다. 옛 구현은 마지막
 * 프레임이 opacity 0 이라 그냥 두어도 됐다. globals.css 의 `vx-out` 이
 * 그 자리다.
 *
 * **어둡게 깔기(vx-dim)는 장식이 아니라 판정을 감추는 장치다.** 스포트라이트가
 * `--background` 로 시작해 66%에 색이 바뀌는데, 어둡지 않으면 그 전환이 안
 * 보인다. 66% 전에는 결과를 모르는 것이 이 연출의 요점이다.
 *
 * ## 어둡게 까는 것은 멈추는 화면에서만
 *
 * 그런데 **답한 뒤 멈추지 않는 화면에서는 그 장치가 해가 된다.**
 *
 * 일일학습·복습은 답하면 곧바로 다음 문제가 뜬다. 연출은 1초 도는데 그
 * 사이 다음 문제와 결과 줄이 이미 화면에 있고, 둘 다 읽어야 하는 것인데
 * 어둡다. **결정적인 것은 이 층이 `pointer-events: none` 이라 어두운 동안에도
 * 보기 버튼이 눌린다는 점이다** - 빨리 푸는 사람은 어두운 화면에서 다음 답을
 * 고르게 된다.
 *
 * 그래서 기준을 "멈추는 화면인가" 로 둔다.
 *
 *     멈추는 화면    문제풀기 · 판 모드      어둡게 깐다
 *     안 멈추는 화면  일일학습 · 복습         안 깐다
 *
 * **기본값을 두지 않는다.** 호출부가 매번 고르게 한다 - 이유는 아래 prop
 * 주석에 있다.
 *
 * ## props 를 바꾸면 네 화면이 깨진다
 *
 * `QuizBoard`·`RoundBoard`·`DailyStudyBoard`·`ReviewBoard` 가 이 모양으로
 * 부른다. 안은 통째로 바꿔도 되지만 **바깥 모양은 계약이다.**
 *
 * ## 'use client' 를 붙인 이유
 *
 * `useId()` 를 쓴다. 원본은 그라디언트 id 를 모듈 최상위 카운터로 만드는데,
 * 서버에서도 한 번 그려지는 이 저장소에서는 **서버·클라이언트의 카운터가
 * 갈려 hydration 이 어긋난다.** 자세한 것은 ReactionCharacters 머리말에 있다.
 *
 * 전에는 'use client' 가 없었다. 상태도 이벤트도 없어서 필요가 없었는데,
 * 훅을 쓰는 순간 클라이언트 경계가 필요하다.
 */

type Props = {
  /** 재생 횟수. 채점할 때마다 1 씩 올린다. 0 이면 아무것도 안 그린다. */
  fire: number;
  /** 맞혔는가. 쓰다듬기와 콩을 가른다. */
  correct: boolean;
  /**
   * 화면을 어둡게 깔지. **답한 뒤 멈추는 화면에서만 켠다.**
   *
   * 기본값을 안 둔 것은 일부러다. 안 멈추는 화면이 기본값을 물려받으면
   * 곧바로 "안 읽히는데 눌리는 1초" 가 되는데, 앞으로 붙을 화면은 대개
   * 탭바가 있는 일반 화면 - 즉 다수가 `false` 쪽이다. 필수로 두면 다섯
   * 번째 화면이 컴파일 단계에서 판단을 강요받는다.
   *
   * 끄면 어둠·무대·판정 글자 셋이 빠지고 링과 캐릭터만 돈다.
   */
  dim: boolean;
};

export function Reaction({ fire, correct, dim }: Props) {
  // 그라디언트 id 를 가르는 값. 같은 화면에 둘이 그려져도 색이 안 섞인다.
  const gid = useId();

  if (fire === 0) return null;

  return (
    // key 로 횟수를 넘겨 매번 새로 마운트시킨다. 클래스만 토글하면 연속으로
    // 맞혔을 때 두 번째부터 애니메이션이 안 뛴다.
    //
    // aria-hidden: 채점 결과는 이미 글자로 전달된다. 여기서 또 알리면 같은
    // 말이 두 번 나온다.
    <div
      key={fire}
      aria-hidden
      className={`vx ${correct ? "vx-ok" : "vx-no"}`}
      style={
        {
          // 판정 색. 무대 바닥과 링이 이 값을 쓴다.
          "--vx-color": correct ? "var(--correct-deep)" : "var(--wrong-deep)",
          // 팔 동작과 학생 반응. CSS 가 이 이름으로 키프레임을 고른다.
          "--vx-arm": correct ? "vx-pat" : "vx-bonk",
          "--vx-stu": correct ? "vx-happy" : "vx-ouch",
        } as React.CSSProperties
      }
    >
      {/* 어둡게 깔기 · 무대 · 퍼지는 링. 순서가 곧 겹치는 순서다.

          **무대도 어둠을 따라간다.** 무대는 알파 없는 크림 원반이라, 어둠
          위에 얹히면 스포트라이트가 되지만 밝은 화면에 그대로 얹히면 300px
          짜리 가림막이 된다. 이 층은 pointer-events: none 이라 가린 채로
          눌린다 - 어둠을 뺀 이유와 같은 이유로 무대도 뺀다.

          링은 테두리라 안이 비어 있어서 어느 화면에서든 돈다. 어둠을 끈
          화면에서 판정을 전달하는 것이 이 링과 표정이다. */}
      {dim && <div className="vx-dim" />}
      {dim && <div className="vx-spot" />}
      <div className="vx-ring" />

      {/* 무대는 화면 정중앙이다. **안 멈추는 화면에서는 이 자리가 본문을
          가린다** - 390x844 일일학습에서 재보면 사람이 y 302~493 을 차지해
          새 문제 설명의 끝부분과 첫 보기(y 433~489)를 1초 동안 덮는다.
          보기 글자는 x 36 에서 시작하고 사람은 x 83~288 이라, 보기의 첫
          몇 글자는 보인다.

          **옛 졸라맨은 이 자리를 피해 아래에 세웠다.** 그 주석이 이번
          이식에서 근거째로 사라졌는데, 여기 다시 적는다 - 되살리지 않는
          것은 새 연출에서 피할 자리가 없기 때문이다. 폰 화면에 빈 곳이
          없다. 아래로 내리면 보기 버튼을 덮고, 위로 올리면 결과 줄과 문제
          카드를 통째로 덮는다.

          가운데를 고른 이유: 덮이는 것이 **방금 답한 결과가 아니라 아직
          안 읽은 다음 문제**다. 사용자는 그 1초 동안 결과 줄(문제 카드
          위, 390x844 에서 y 91~131 - 안 덮인다)을 본다. 다음 문제로 눈이
          가는 시점에는 연출이 끝나 있다.

          줄이거나 구석으로 보내는 안은 일부러 안 골랐다. 판 모드와 다른
          연출이 되어, 같은 판정을 화면마다 다르게 배우게 된다. */}
      <svg viewBox="0 0 300 300">
        {/* 바닥 그림자. 둘이 같은 바닥에 서 있다는 것을 만든다. */}
        <ellipse cx="150" cy="262" rx="110" ry="8" fill="rgba(0,0,0,.12)" />
        {/* 학생이 먼저다. 부장님이 오른쪽에서 겹칠 때 팔이 위로 와야 한다. */}
        <g transform="translate(200,256)">
          <g className="stu">
            <Student gid={`${gid}s`} expr="idle" />
          </g>
        </g>
        <g transform="translate(96,256)">
          <g className="boss">
            <Boss gid={`${gid}b`} expr="neutral" />
          </g>
        </g>
      </svg>

      {/* 판정 글자. **어둠과 함께 켜고 함께 끈다.**
          보기 버튼의 정답 표시와 해설 카드가 같은 말을 하지만, 어둠이 깔린
          동안에는 그 둘이 안 읽힌다. 그 사이를 메우고 74~92% 에 사라진다 -
          어둠이 걷힌 뒤에 남으면 그때부터는 진짜 중복이다.

          어둠이 없으면 이 글자를 안 그리는 이유가 둘이다. 하나는 위 근거가
          사라지는 것이고(가리는 것이 없으니 메울 것도 없다), 하나는 **흰
          글자라 크림 바탕에서 안 읽히는 것**이다. 어둠 위에 얹힐 것을
          전제한 색이다.

          그 화면들은 결과 줄을 따로 갖고 있고, 판정 자체는 링이 판정색으로
          터지는 것과 표정이 바뀌는 것으로 전달된다. */}
      {dim && (
        <p className="vx-verdict">{correct ? "맞았습니다" : "틀렸습니다"}</p>
      )}
    </div>
  );
}

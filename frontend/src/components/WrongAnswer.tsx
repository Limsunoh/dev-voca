/**
 * 틀렸을 때 보여주는 정답 줄.
 *
 * 한 판·일일학습·복습이 같이 쓴다. 세 화면 모두 결과를 한 줄로만 알리고
 * 해설 카드가 없어서, 여기서 안 보여주면 **정답의 뜻을 끝내 못 본다.**
 * 서버는 처음부터 뜻을 같이 내려보내고 있었다(learning/views.py 의
 * answer_extra). 화면이 영어만 그리고 뜻을 버렸다.
 *
 * 특히 "이 단어의 뜻은?" 처럼 뜻을 고르는 문제에서 그렇다. 틀린 사람이
 * 받는 것이 영어 단어 하나뿐이라, 정작 고르려던 뜻은 화면 어디에도 없다.
 *
 * QuestionCard 에 두지 않는 이유: 그쪽은 "정답/오답 다음에 무엇을 덧붙이나"
 * 가 화면마다 달라서 결과 문구를 일부러 안 받는다(그 파일 머리말). 여기는
 * 세 화면이 똑같이 쓰는 오답 부분만 담는다.
 *
 * 문제풀기(QuizBoard)는 안 쓴다. 거기는 답을 고르면 뜻·발음·예문이 있는
 * 해설 카드가 통째로 열린다.
 */
export function WrongAnswer({
  label = "오답",
  text,
  extra,
}: {
  /**
   * 앞에 붙는 말.
   *
   * 한 판에서 넘긴 문제는 "넘김" 이다. 넘긴 것은 틀린 것이 아니라 점수도
   * 안 깎이는데(0점) "오답" 이라고 하면 벌처럼 읽힌다. 서버는 넘긴 답에도
   * 정답을 실어 보낸다 - 모르는 문제를 넘긴 사람이야말로 정답이 필요하다.
   */
  label?: string;
  /** 정답의 본문. 단어면 영어 단어, 문장이면 그 문장. */
  text: string;
  /** 정답의 뜻. 단어면 뜻, 문장이면 해석. */
  extra: string;
}) {
  // 검수가 취소되면 서버가 둘 다 빈 값으로 준다(session.py 의 _describe).
  // 그때 "오답 · " 로 끝나면 뒤가 잘린 것처럼 보인다.
  //
  // **뜻만 남는 경우가 따로 있다.** 문장 문제의 본문은 "나오는 상황" 인데,
  // 관리자가 그것을 비우면 본문만 빈 채 해석은 남는다. 여기서 둘을 같이
  // 버리면 서버가 보낸 뜻이 화면에서 사라져, 이 조각을 만든 이유가 그
  // 경우에만 무효가 된다.
  // **공백을 깎고 본다.** 빈 값만 막으면 공백 한 칸은 통과해 "오답 · " 로
  // 끝난다. Admin 폼은 공백을 깎지만 시드나 AI 파이프라인처럼 폼을 안 타는
  // 쓰기는 그대로 들어온다.
  const answer = text.trim();
  const meaning = extra.trim();

  if (!answer && !meaning) return <>{label}</>;

  return (
    <>
      {label}
      {answer && ` · ${answer}`}
      {meaning && (
        // 블록이 아니라 span 인 이유: 호출부가 이 줄을 <p> 안에 넣는다.
        // <p> 안에는 <div> 를 못 넣는다.
        <span
          style={{
            display: "block",
            color: "var(--text-muted)",
            fontWeight: "var(--weight-bold)",
          }}
        >
          {meaning}
        </span>
      )}
    </>
  );
}

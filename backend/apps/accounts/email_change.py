"""이메일 변경의 본인 확인.

## 왜 바로 안 바꾸나

이메일은 로그인 키다. 확인 없이 바꾸게 두면 계정을 통째로 넘기는 통로가
된다 - 로그인된 화면을 잠깐 빌리기만 해도 제 주소로 바꿔 가져갈 수 있고,
원래 주인은 자기 주소로 더는 못 들어온다. 비밀번호를 바꾸는 것보다 나쁘다.
비밀번호는 바뀌어도 계정은 내 것이지만, 이메일이 바뀌면 계정 자체가 남의
것이 된다.

그래서 **새 주소로 확인 메일을 보내고, 그 링크를 눌러야 바뀐다.** 링크를
누를 수 있다는 것이 그 주소의 주인이라는 증거다.

## 왜 표를 안 만드나

확인 토큰을 담을 모델을 따로 두지 않고 서명한 문자열에 실어 보낸다.
`learning/session.py` 가 판 토큰에 쓰는 방식과 같다. 표를 두면 만료된 행을
치우는 일이 따로 생기고, 그 청소가 밀리면 쓰지도 않을 행이 쌓인다.

서명에는 바꿀 주소와 사용자 번호가 들어간다. 서버 키로 서명하므로 내용을
고치면 검증에서 걸린다.

## 옛 주소를 함께 넣는 이유

토큰에 **지금 주소도 같이** 담고, 쓸 때 현재 값과 맞는지 본다. 안 담으면
이런 일이 생긴다 - a→b 로 바꾸는 링크를 받아두고, 그 사이 a→c 로 바꾼 뒤,
묵혀둔 링크를 누르면 c 가 b 로 되돌아간다. 사용자는 바꾼 적 없는 주소로
계정이 옮겨간 것을 나중에야 안다.

## 비밀번호를 함께 확인하는 이유

토큰을 보내기 전에 현재 비밀번호를 묻는다. 링크는 새 주소의 주인임을
증명할 뿐, **지금 화면 앞에 있는 사람이 계정 주인인지는 증명하지 않는다.**
자리를 비운 사이 남이 제 주소로 변경을 걸어두면, 그 사람은 제 메일함에서
링크를 눌러 계정을 가져간다. 둘 다 있어야 막힌다.
"""

from __future__ import annotations

from django.core import signing

# 확인 링크의 수명. 짧게 두면 메일을 늦게 여는 사람이 다시 요청해야 하고,
# 길게 두면 새어나간 링크가 오래 살아 있다. 메일을 확인하는 데 걸리는
# 현실적인 시간을 생각해 하루로 둔다.
TOKEN_MAX_AGE = 60 * 60 * 24

# 서명 용도를 가르는 이름. 다른 곳에서 만든 서명이 여기서 통하지 않게 한다.
# 없으면 같은 키로 서명한 다른 토큰(판 토큰 등)을 여기 밀어 넣을 여지가 생긴다.
_SALT = "accounts.email_change"


class InvalidToken(Exception):
    """확인 링크가 만료됐거나 손상됐거나 이미 쓸 수 없는 상태다."""


def make_token(*, user_id: int, current_email: str, new_email: str) -> str:
    """확인 링크에 실을 토큰.

    주소를 저장할 때와 같은 방식으로 소문자로 내려 담는다. 안 그러면
    대문자로 신청한 사람이 링크를 눌렀을 때 현재 주소와 안 맞아 거절된다.
    """
    return signing.dumps(
        {
            "u": user_id,
            # 신청 당시의 주소. 쓸 때 현재 값과 비교한다.
            "o": current_email.lower(),
            "n": new_email.lower(),
        },
        salt=_SALT,
    )


def read_token(token: str) -> tuple[int, str, str]:
    """토큰에서 (사용자 번호, 옛 주소, 새 주소) 를 꺼낸다.

    만료와 위조를 여기서 함께 거른다. 부르는 쪽이 둘을 나눠 처리할 일이
    없다 - 사용자에게는 어느 쪽이든 "링크를 다시 받으세요" 다. 어느 쪽인지
    알려주면 위조를 시도하는 쪽에만 정보가 된다.
    """
    try:
        data = signing.loads(token, salt=_SALT, max_age=TOKEN_MAX_AGE)
    except signing.BadSignature as exc:
        raise InvalidToken("확인 링크가 만료되었거나 올바르지 않습니다.") from exc

    # 서명이 맞아도 모양이 다를 수 있다. 옛 형식으로 만든 토큰이 남아 있는
    # 경우가 그렇다. 그대로 꺼내면 KeyError 가 500 으로 올라간다.
    try:
        return int(data["u"]), str(data["o"]), str(data["n"])
    except (KeyError, TypeError, ValueError) as exc:
        raise InvalidToken("확인 링크가 올바르지 않습니다.") from exc


def build_mail(*, link: str) -> tuple[str, str]:
    """확인 메일의 (제목, 본문).

    링크만 덩그러니 보내지 않는다. 받는 사람 입장에서 이 메일은 신청하지
    않았는데 온 것일 수 있다 - 남이 내 주소를 남의 계정에 붙이려 한 경우다.
    그때 무엇을 해야 하는지(아무것도 안 하면 된다) 를 적어야 한다.
    """
    subject = "[devvoca] 이메일 변경 확인"
    body = (
        "devvoca 계정의 이메일을 이 주소로 바꾸려는 요청이 있었습니다.\n"
        "아래 링크를 열면 변경이 끝납니다.\n\n"
        f"{link}\n\n"
        "링크는 하루가 지나면 쓸 수 없습니다.\n\n"
        "이 요청을 한 적이 없다면 아무것도 하지 않으셔도 됩니다. "
        "링크를 열지 않으면 아무 일도 일어나지 않습니다.\n"
    )
    return subject, body

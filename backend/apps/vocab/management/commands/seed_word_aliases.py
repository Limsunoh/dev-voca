class Command(BaseCommand):
    help = "단어에 검색용 한글 표기를 채웁니다."

    def add_arguments(self, parser: CommandParser) -> None:
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="저장하지 않고 개수만 보여줍니다.",
        )
        parser.add_argument(
            "--reset",
            action="store_true",
            help="이미 적힌 표기도 이 파일 값으로 덮어씁니다.",
        )

    @transaction.atomic
    def handle(self, *args, **options) -> None:
        words = list(Word.objects.filter(term__in=ALIASES))
        targets = words if options["reset"] else [w for w in words if not w.aliases]
        for word in targets:
            word.aliases = ALIASES[word.term]

        if not options["dry_run"]:
            Word.objects.bulk_update(targets, ["aliases"])

        missing = sorted(ALIASES.keys() - {word.term for word in words})
        self.stdout.write(
            f"채움 {len(targets)}, 그대로 {len(words) - len(targets)}, DB 에 없음 {len(missing)}"
        )
        for term in missing:
            self.stdout.write(f"  없음: {term}")
        if options["dry_run"]:
            self.stdout.write(self.style.WARNING("--dry-run 이라 저장하지 않았습니다."))
